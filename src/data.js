function buildQuestions(gradeKey, seeds) {
  const questions = [];
  let serial = 1;
  // 42 authored cards × 12 different prompt surfaces = 504, trimmed to 500.
  QUESTION_TEMPLATES.forEach((template, templateIndex) => {
    seeds.forEach((seed, seedIndex) => {
      const sentence = `「${seed.word}」という言葉を、文の中で正しく使おう。`;
      questions.push({
        id: `${gradeKey}-${String(serial++).padStart(3, '0')}`,
        grade: gradeKey,
        word: seed.word,
        reading: seed.reading,
        meaning: seed.meaning,
        prompt: template.replace('__WORD__', seed.word),
        sentence,
        templateIndex,
        seedIndex,
      });
    });
  });
  // A few grades have a different number of authored cards; top them up with
  // explicitly labelled recall cards so every grade always exposes 500 items.
  while (questions.length < 500) {
    const seed = seeds[questions.length % seeds.length];
    questions.push({
      id: `${gradeKey}-${String(serial++).padStart(3, '0')}`,
      grade: gradeKey,
      word: seed.word,
      reading: seed.reading,
      meaning: seed.meaning,
      prompt: `リコールカード ${questions.length + 1}：${seed.word}`,
      sentence: `「${seed.word}」という言葉を、文の中で正しく使おう。`,
      templateIndex: -1,
      seedIndex: questions.length % seeds.length,
    });
  }
  return questions.slice(0, 500);
}

export const QUESTION_BANKS = Object.fromEntries(
  Object.entries(SEED_BLOCKS).map(([grade, block]) => [grade, buildQuestions(grade, parseSeeds(block))]),
);

export function getQuestionsForGrade(gradeKey) {
  return QUESTION_BANKS[String(gradeKey)] ?? QUESTION_BANKS['5'];
}

export function getGrade(gradeKey) {
  return GRADE_CONFIG.find((grade) => grade.key === String(gradeKey)) ?? GRADE_CONFIG[6];
}

export function getRandomQuestions(gradeKey, amount = 5) {
  const source = [...getQuestionsForGrade(gradeKey)];
  for (let index = source.length - 1; index > 0; index -= 1) {
    const swapIndex = Math.floor(Math.random() * (index + 1));
    [source[index], source[swapIndex]] = [source[swapIndex], source[index]];
  }
  return source.slice(0, amount);
}

